#!/usr/bin/env python3
"""Authoring tool for Wayfinder decision cards.

    python3 tools/cards.py check     validate every card and the index
    python3 tools/cards.py index     regenerate INDEX.md
    python3 tools/cards.py status    list cards as fresh, expiring or stale

Needs PyYAML. Not shipped with the plugin. The rules are in docs/spec.md, section 3.
"""

import argparse
import datetime
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CARDS_DIR = REPO / "plugin" / "skills" / "route" / "cards"
INDEX_NAME = "INDEX.md"
INDEX_HEADER = (
    "<!-- Generated by tools/cards.py index. Do not edit by hand. -->\n"
    "| id | kind | when | verdict | expires |\n"
    "| :- | :- | :- | :- | :- |\n"
)

REQUIRED = [
    "id", "kind", "symptom", "triggers", "verdict", "do", "alternative", "skip",
    "supersedes", "ring", "trust", "always_on_cost", "executes", "install", "undo",
    "verified", "ttl_days", "sources",
]
ENUMS = {
    "kind": {"method", "capability"},
    "verdict": {"built-in", "official-plugin", "pick", "nothing-needed"},
    "ring": {"adopt", "trial", "assess", "hold"},
    "trust": {"official", "verified", "third-party"},
    "always_on_cost": {"none", "low", "medium", "high"},
}
INSTALL_VERDICTS = {"official-plugin", "pick"}
INSTALL_FIELDS = ["executes", "install", "undo"]
HEADINGS = ["## Pattern", "## Claude Code recipe", "## Why skip the others", "## Evidence"]
MAX_LINES = 80
WARN_DAYS = 14


def split_card(text):
    """Return (front matter text, body). Raise ValueError if there is no front matter."""
    if not text.startswith("---\n"):
        raise ValueError("the file does not start with a front matter block")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError("the front matter block is not closed")
    return text[4:end], text[end + 5:]


def load_card(path):
    """Return (meta, body, errors). meta is None when the front matter can't be read."""
    import yaml

    text = Path(path).read_text(encoding="utf-8")
    try:
        front, body = split_card(text)
        meta = yaml.safe_load(front)
    except (ValueError, yaml.YAMLError) as exc:
        return None, text, [f"front matter: {exc}"]
    if not isinstance(meta, dict):
        return None, text, ["front matter: not a mapping"]
    return meta, body, []


def _is_text(value):
    return isinstance(value, str) and value.strip() != ""


def _is_text_list(value):
    return isinstance(value, list) and all(_is_text(item) for item in value)


def validate(meta, body, name, line_count, today):
    """Return the list of rule violations for one card. `name` is the file name without .md."""
    errors = [f"missing field: {key}" for key in REQUIRED if key not in meta]
    if errors:
        return errors

    for key, allowed in ENUMS.items():
        if meta[key] not in allowed:
            errors.append(f"{key}: {meta[key]!r} is not one of {sorted(allowed)}")

    if meta["id"] != name:
        errors.append(f"id: {meta['id']!r} does not match the file name {name!r}")
    for key in ("symptom", "do"):
        if not _is_text(meta[key]):
            errors.append(f"{key}: must be a non-empty string")
    if meta["alternative"] is not None and not _is_text(meta["alternative"]):
        errors.append("alternative: must be a string or null")
    for key in ("triggers", "skip", "supersedes", "sources"):
        if not _is_text_list(meta[key]):
            errors.append(f"{key}: must be a list of strings")

    if _is_text_list(meta["triggers"]) and not 2 <= len(meta["triggers"]) <= 6:
        errors.append(f"triggers: {len(meta['triggers'])} entries, expected 2 to 6")
    if _is_text_list(meta["sources"]):
        if not meta["sources"]:
            errors.append("sources: at least one URL is required")
        for url in meta["sources"]:
            if not url.startswith(("https://", "http://")):
                errors.append(f"sources: {url!r} is not a URL")

    pipe_fields = [meta["symptom"]] if _is_text(meta["symptom"]) else []
    pipe_fields += meta["triggers"] if _is_text_list(meta["triggers"]) else []
    if any("|" in value for value in pipe_fields):
        errors.append("symptom and triggers must not contain '|'")

    if not isinstance(meta["verified"], datetime.date):
        errors.append("verified: must be a date written as YYYY-MM-DD")
    elif meta["verified"] > today:
        errors.append(f"verified: {meta['verified']} is in the future")
    if not isinstance(meta["ttl_days"], int) or isinstance(meta["ttl_days"], bool) or meta["ttl_days"] < 1:
        errors.append("ttl_days: must be a positive whole number")

    if meta["verdict"] in INSTALL_VERDICTS:
        errors += [
            f"{key}: required when the verdict is {meta['verdict']}"
            for key in INSTALL_FIELDS
            if not _is_text(meta[key])
        ]
    elif meta["verdict"] in ENUMS["verdict"]:
        errors += [
            f"{key}: must be null when the verdict is {meta['verdict']}"
            for key in INSTALL_FIELDS
            if meta[key] is not None
        ]

    body_lines = body.splitlines()
    errors += [f"body: missing the heading {heading!r}" for heading in HEADINGS if heading not in body_lines]
    if line_count > MAX_LINES:
        errors.append(f"{line_count} lines, the limit is {MAX_LINES}")
    return errors


def expires(meta):
    return meta["verified"] + datetime.timedelta(days=meta["ttl_days"])


def state(meta, today):
    """Return 'fresh', 'expiring' (within WARN_DAYS) or 'stale'."""
    days_left = (expires(meta) - today).days
    if days_left < 0:
        return "stale"
    return "expiring" if days_left <= WARN_DAYS else "fresh"


def when_text(meta):
    triggers = "; ".join(f'"{trigger}"' for trigger in meta["triggers"])
    symptom = meta["symptom"].rstrip(".")
    return f"{symptom}. {triggers}"


def render_index(cards):
    """cards: list of meta dicts that passed validation."""
    rows = [
        f"| {meta['id']} | {meta['kind']} | {when_text(meta)} | {meta['verdict']} | {expires(meta)} |\n"
        for meta in sorted(cards, key=lambda meta: meta["id"])
    ]
    return INDEX_HEADER + "".join(rows)


def collect(cards_dir, today):
    """Return (valid metas, {file name: [errors]})."""
    valid, problems = [], {}
    for path in sorted(Path(cards_dir).glob("*.md")):
        if path.name == INDEX_NAME:
            continue
        meta, body, errors = load_card(path)
        if meta is not None:
            line_count = len(path.read_text(encoding="utf-8").splitlines())
            errors = validate(meta, body, path.stem, line_count, today)
        if errors:
            problems[path.name] = errors
        else:
            valid.append(meta)
    return valid, problems


def cmd_check(cards_dir, today):
    valid, problems = collect(cards_dir, today)
    for name, errors in problems.items():
        for error in errors:
            print(f"ERROR {name}: {error}")

    index_path = Path(cards_dir) / INDEX_NAME
    index_ok = True
    if not problems:
        current = index_path.read_text(encoding="utf-8") if index_path.exists() else None
        if current != render_index(valid):
            index_ok = False
            print(f"ERROR {INDEX_NAME}: out of date. Run: python3 tools/cards.py index")

    for meta in valid:
        card_state = state(meta, today)
        if card_state != "fresh":
            print(f"WARN  {meta['id']}: {card_state}, review date {expires(meta)}")

    if problems or not index_ok:
        return 1
    print(f"OK    {len(valid)} cards, index current")
    return 0


def cmd_index(cards_dir, today):
    valid, problems = collect(cards_dir, today)
    if problems:
        for name, errors in problems.items():
            for error in errors:
                print(f"ERROR {name}: {error}")
        print("Index not written. Fix the cards first.")
        return 1
    (Path(cards_dir) / INDEX_NAME).write_text(render_index(valid), encoding="utf-8")
    print(f"Wrote {INDEX_NAME} with {len(valid)} cards")
    return 0


def cmd_status(cards_dir, today):
    valid, problems = collect(cards_dir, today)
    print(f"{'id':<28} {'verdict':<16} {'verified':<11} {'expires':<11} state")
    for meta in sorted(valid, key=lambda meta: meta["id"]):
        print(
            f"{meta['id']:<28} {meta['verdict']:<16} {meta['verified']!s:<11} "
            f"{expires(meta)!s:<11} {state(meta, today)}"
        )
    for name in problems:
        print(f"{name:<28} invalid, run check")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description="Check and index Wayfinder decision cards.")
    parser.add_argument("command", choices=["check", "index", "status"])
    parser.add_argument("--cards-dir", default=str(CARDS_DIR), help="directory holding the card files")
    parser.add_argument("--today", help="override today's date (YYYY-MM-DD), for testing")
    args = parser.parse_args(argv)
    today = datetime.date.fromisoformat(args.today) if args.today else datetime.date.today()
    command = {"check": cmd_check, "index": cmd_index, "status": cmd_status}[args.command]
    return command(args.cards_dir, today)


if __name__ == "__main__":
    sys.exit(main())
