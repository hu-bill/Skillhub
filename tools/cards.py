#!/usr/bin/env python3
"""Authoring tool for Wayfinder decision cards (Pi primary, Claude Code preserved).

    python3 tools/cards.py check [--target pi|claude|all]    validate cards, index and fixtures
    python3 tools/cards.py index [--target pi|claude|all]    regenerate INDEX.md
    python3 tools/cards.py status [--target pi|claude|all]   list cards as fresh, expiring or stale
    python3 tools/cards.py fixture [--target pi|claude|all]  regenerate stale-card test fixtures

Needs PyYAML. Not shipped with the package. The rules are in docs/spec.md, section 3.
"""

import argparse
import datetime
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

PI_PACKAGE_DIR = REPO / "pi-package"
PI_CARDS_DIR = PI_PACKAGE_DIR / "skills" / "route" / "cards"
PI_FIXTURE_DIR = PI_PACKAGE_DIR / "fixtures" / "stale-package"
PI_FIXTURE_COPIES = [
    "package.json",
    "extensions/index.ts",
    "skills/route/SKILL.md",
    "skills/route/RUBRIC.md",
    "bin/wayfinder",
    "agents/scout.md",
]
PI_FIXTURE_STALE_CARD = "long-sessions-degrade"

CLAUDE_PLUGIN_DIR = REPO / "plugin"
CLAUDE_CARDS_DIR = CLAUDE_PLUGIN_DIR / "skills" / "route" / "cards"
CLAUDE_FIXTURE_DIR = CLAUDE_PLUGIN_DIR / "fixtures" / "stale-plugin"
CLAUDE_FIXTURE_COPIES = [".claude-plugin/plugin.json", "skills/route/SKILL.md", "skills/route/RUBRIC.md"]
CLAUDE_FIXTURE_STALE_CARD = "plan-large-feature"

# Primary v1 target is Pi. Kept as module constants for callers and unit tests.
CARDS_DIR = PI_CARDS_DIR
FIXTURE_DIR = PI_FIXTURE_DIR
FIXTURE_VERIFIED = "2026-01-01"

INDEX_NAME = "INDEX.md"
INDEX_HEADER = (
    "<!-- Generated by tools/cards.py index. Do not edit by hand. -->\n"
    "| id | kind | when | verdict | expires |\n"
    "| :- | :- | :- | :- | :- |\n"
)

REQUIRED = [
    "id", "kind", "symptom", "triggers", "verdict", "do", "alternative", "skip",
    "supersedes", "ring", "trust", "always_on_cost", "executes", "install", "undo",
    "verified", "ttl_days", "sources",
]
ENUMS = {
    "kind": {"method", "capability"},
    "verdict": {"built-in", "official-plugin", "pick", "nothing-needed"},
    "ring": {"adopt", "trial", "assess", "hold"},
    "trust": {"official", "verified", "third-party"},
    "always_on_cost": {"none", "low", "medium", "high"},
}
INSTALL_VERDICTS = {"official-plugin", "pick"}
INSTALL_FIELDS = ["executes", "install", "undo"]
PI_RECIPE_HEADING = "## Pi recipe"
CLAUDE_RECIPE_HEADING = "## Claude Code recipe"
RECIPE_HEADINGS = (PI_RECIPE_HEADING, CLAUDE_RECIPE_HEADING)
HEADINGS = ["## Pattern", PI_RECIPE_HEADING, "## Why skip the others", "## Evidence"]
MAX_LINES = 80
WARN_DAYS = 14

TARGETS = {
    "pi": {
        "label": "pi",
        "root_dir": PI_PACKAGE_DIR,
        "cards_dir": PI_CARDS_DIR,
        "fixture_dir": PI_FIXTURE_DIR,
        "fixture_copies": PI_FIXTURE_COPIES,
        "stale_card": PI_FIXTURE_STALE_CARD,
        "recipe_heading": PI_RECIPE_HEADING,
    },
    "claude": {
        "label": "claude",
        "root_dir": CLAUDE_PLUGIN_DIR,
        "cards_dir": CLAUDE_CARDS_DIR,
        "fixture_dir": CLAUDE_FIXTURE_DIR,
        "fixture_copies": CLAUDE_FIXTURE_COPIES,
        "stale_card": CLAUDE_FIXTURE_STALE_CARD,
        "recipe_heading": CLAUDE_RECIPE_HEADING,
    },
}


def target_for_cards_dir(cards_dir):
    resolved = Path(cards_dir).resolve()
    for cfg in TARGETS.values():
        if resolved == cfg["cards_dir"].resolve():
            return cfg
    return None


def split_card(text):
    """Return (front matter text, body). Raise ValueError if there is no front matter."""
    if not text.startswith("---\n"):
        raise ValueError("the file does not start with a front matter block")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError("the front matter block is not closed")
    return text[4:end], text[end + 5:]


def load_card(path):
    """Return (meta, body, errors). meta is None when the front matter can't be read."""
    import yaml

    text = Path(path).read_text(encoding="utf-8")
    try:
        front, body = split_card(text)
        meta = yaml.safe_load(front)
    except (ValueError, yaml.YAMLError) as exc:
        return None, text, [f"front matter: {exc}"]
    if not isinstance(meta, dict):
        return None, text, ["front matter: not a mapping"]
    return meta, body, []


def _is_text(value):
    return isinstance(value, str) and value.strip() != ""


def _is_text_list(value):
    return isinstance(value, list) and all(_is_text(item) for item in value)


def validate(meta, body, name, line_count, today, recipe_heading=None):
    """Return the list of rule violations for one card. `name` is the file name without .md."""
    errors = [f"missing field: {key}" for key in REQUIRED if key not in meta]
    if errors:
        return errors

    for key, allowed in ENUMS.items():
        if meta[key] not in allowed:
            errors.append(f"{key}: {meta[key]!r} is not one of {sorted(allowed)}")

    if meta["id"] != name:
        errors.append(f"id: {meta['id']!r} does not match the file name {name!r}")
    for key in ("symptom", "do"):
        if not _is_text(meta[key]):
            errors.append(f"{key}: must be a non-empty string")
    if meta["alternative"] is not None and not _is_text(meta["alternative"]):
        errors.append("alternative: must be a string or null")
    for key in ("triggers", "skip", "supersedes", "sources"):
        if not _is_text_list(meta[key]):
            errors.append(f"{key}: must be a list of strings")

    if _is_text_list(meta["triggers"]) and not 2 <= len(meta["triggers"]) <= 6:
        errors.append(f"triggers: {len(meta['triggers'])} entries, expected 2 to 6")
    if _is_text_list(meta["sources"]):
        if not meta["sources"]:
            errors.append("sources: at least one URL is required")
        for url in meta["sources"]:
            if not url.startswith(("https://", "http://")):
                errors.append(f"sources: {url!r} is not a URL")

    pipe_fields = [meta["symptom"]] if _is_text(meta["symptom"]) else []
    pipe_fields += meta["triggers"] if _is_text_list(meta["triggers"]) else []
    if any("|" in value for value in pipe_fields):
        errors.append("symptom and triggers must not contain '|'")

    if not isinstance(meta["verified"], datetime.date):
        errors.append("verified: must be a date written as YYYY-MM-DD")
    elif meta["verified"] > today:
        errors.append(f"verified: {meta['verified']} is in the future")
    if not isinstance(meta["ttl_days"], int) or isinstance(meta["ttl_days"], bool) or meta["ttl_days"] < 1:
        errors.append("ttl_days: must be a positive whole number")

    if meta["verdict"] in INSTALL_VERDICTS:
        errors += [
            f"{key}: required when the verdict is {meta['verdict']}"
            for key in INSTALL_FIELDS
            if not _is_text(meta[key])
        ]
    elif meta["verdict"] in ENUMS["verdict"]:
        errors += [
            f"{key}: must be null when the verdict is {meta['verdict']}"
            for key in INSTALL_FIELDS
            if meta[key] is not None
        ]

    body_lines = body.splitlines()
    if "## Pattern" not in body_lines:
        errors.append("body: missing the heading '## Pattern'")
    if recipe_heading is not None:
        if recipe_heading not in body_lines:
            errors.append(f"body: missing the heading {recipe_heading!r}")
    elif not any(h in body_lines for h in RECIPE_HEADINGS):
        errors.append(f"body: missing the heading {PI_RECIPE_HEADING!r}")
    for heading in ("## Why skip the others", "## Evidence"):
        if heading not in body_lines:
            errors.append(f"body: missing the heading {heading!r}")

    if line_count > MAX_LINES:
        errors.append(f"{line_count} lines, the limit is {MAX_LINES}")
    return errors


def expires(meta):
    return meta["verified"] + datetime.timedelta(days=meta["ttl_days"])


def state(meta, today):
    """Return 'fresh', 'expiring' (within WARN_DAYS) or 'stale'."""
    days_left = (expires(meta) - today).days
    if days_left < 0:
        return "stale"
    return "expiring" if days_left <= WARN_DAYS else "fresh"


def when_text(meta):
    triggers = "; ".join(f'"{trigger}"' for trigger in meta["triggers"])
    symptom = meta["symptom"].rstrip(".")
    return f"{symptom}. {triggers}"


def render_index(cards):
    """cards: list of meta dicts that passed validation."""
    rows = [
        f"| {meta['id']} | {meta['kind']} | {when_text(meta)} | {meta['verdict']} | {expires(meta)} |\n"
        for meta in sorted(cards, key=lambda meta: meta["id"])
    ]
    return INDEX_HEADER + "".join(rows)


def collect(cards_dir, today, recipe_heading=None):
    """Return (valid metas, {file name: [errors]})."""
    if recipe_heading is None:
        cfg = target_for_cards_dir(cards_dir)
        if cfg is not None:
            recipe_heading = cfg["recipe_heading"]
    valid, problems = [], {}
    for path in sorted(Path(cards_dir).glob("*.md")):
        if path.name == INDEX_NAME:
            continue
        meta, body, errors = load_card(path)
        if meta is not None:
            line_count = len(path.read_text(encoding="utf-8").splitlines())
            errors = validate(meta, body, path.stem, line_count, today, recipe_heading=recipe_heading)
        if errors:
            problems[path.name] = errors
        else:
            valid.append(meta)
    return valid, problems


def fixture_files(root_dir, copies=None, stale_card=None):
    """Return {relative path: text} for a stale-card test package/plugin."""
    import yaml

    root_dir = Path(root_dir)
    if copies is None or stale_card is None:
        if root_dir.resolve() == CLAUDE_PLUGIN_DIR.resolve():
            copies = CLAUDE_FIXTURE_COPIES if copies is None else copies
            stale_card = CLAUDE_FIXTURE_STALE_CARD if stale_card is None else stale_card
        else:
            copies = PI_FIXTURE_COPIES if copies is None else copies
            stale_card = PI_FIXTURE_STALE_CARD if stale_card is None else stale_card

    files = {name: (root_dir / name).read_text(encoding="utf-8") for name in copies}
    metas = []
    for path in sorted((root_dir / "skills" / "route" / "cards").glob("*.md")):
        if path.name == INDEX_NAME:
            continue
        text = path.read_text(encoding="utf-8")
        if path.stem == stale_card:
            text = re.sub(r"^verified: .*$", f"verified: {FIXTURE_VERIFIED}", text, count=1, flags=re.M)
        files[f"skills/route/cards/{path.name}"] = text
        metas.append(yaml.safe_load(split_card(text)[0]))
    files[f"skills/route/cards/{INDEX_NAME}"] = render_index(metas)
    return files


def fixture_is_current(root_dir, fixture_dir, copies=None, stale_card=None):
    fixture_dir = Path(fixture_dir)
    if not fixture_dir.exists():
        return False
    expected = fixture_files(root_dir, copies=copies, stale_card=stale_card)
    on_disk = {
        str(path.relative_to(fixture_dir)): path.read_text(encoding="utf-8")
        for path in fixture_dir.rglob("*")
        if path.is_file()
    }
    return on_disk == expected


def write_fixture_for_target(cfg):
    fixture_dir = cfg["fixture_dir"]
    expected = fixture_files(cfg["root_dir"], copies=cfg["fixture_copies"], stale_card=cfg["stale_card"])
    for path in sorted(fixture_dir.rglob("*"), reverse=True) if fixture_dir.exists() else []:
        if path.is_file() and str(path.relative_to(fixture_dir)) not in expected:
            path.unlink()
    for name, text in expected.items():
        target = fixture_dir / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        src_mode = (cfg["root_dir"] / name).stat().st_mode if (cfg["root_dir"] / name).exists() else None
        if src_mode is not None and (src_mode & 0o111):
            os.chmod(target, src_mode)
    print(f"Wrote {len(expected)} files to {fixture_dir.relative_to(REPO)}")
    return 0


def cmd_fixture(cards_dir, today):
    cfg = target_for_cards_dir(cards_dir) or TARGETS["pi"]
    return write_fixture_for_target(cfg)


def cmd_check(cards_dir, today):
    cfg = target_for_cards_dir(cards_dir)
    prefix = f"[{cfg['label']}] " if cfg else ""
    valid, problems = collect(cards_dir, today)
    for name, errors in problems.items():
        for error in errors:
            print(f"ERROR {prefix}{name}: {error}")

    index_path = Path(cards_dir) / INDEX_NAME
    index_ok = True
    if not problems:
        current = index_path.read_text(encoding="utf-8") if index_path.exists() else None
        if current != render_index(valid):
            index_ok = False
            print(f"ERROR {prefix}{INDEX_NAME}: out of date. Run: python3 tools/cards.py index")

    for meta in valid:
        card_state = state(meta, today)
        if card_state != "fresh":
            print(f"WARN  {prefix}{meta['id']}: {card_state}, review date {expires(meta)}")

    fixture_ok = True
    if not problems and index_ok and cfg is not None:
        if not fixture_is_current(
            cfg["root_dir"],
            cfg["fixture_dir"],
            copies=cfg["fixture_copies"],
            stale_card=cfg["stale_card"],
        ):
            fixture_ok = False
            print(f"ERROR {prefix}stale-card fixture: out of date. Run: python3 tools/cards.py fixture")

    if problems or not index_ok or not fixture_ok:
        return 1
    print(f"OK    {prefix}{len(valid)} cards, index current")
    return 0


def cmd_index(cards_dir, today):
    cfg = target_for_cards_dir(cards_dir)
    prefix = f"[{cfg['label']}] " if cfg else ""
    valid, problems = collect(cards_dir, today)
    if problems:
        for name, errors in problems.items():
            for error in errors:
                print(f"ERROR {prefix}{name}: {error}")
        print(f"{prefix}Index not written. Fix the cards first.")
        return 1
    (Path(cards_dir) / INDEX_NAME).write_text(render_index(valid), encoding="utf-8")
    print(f"Wrote {prefix}{INDEX_NAME} with {len(valid)} cards")
    return 0


def cmd_status(cards_dir, today):
    cfg = target_for_cards_dir(cards_dir)
    if cfg:
        print(f"Target: {cfg['label']} ({cfg['cards_dir'].relative_to(REPO)})")
    valid, problems = collect(cards_dir, today)
    print(f"{'id':<28} {'verdict':<16} {'verified':<11} {'expires':<11} state")
    for meta in sorted(valid, key=lambda meta: meta["id"]):
        print(
            f"{meta['id']:<28} {meta['verdict']:<16} {meta['verified']!s:<11} "
            f"{expires(meta)!s:<11} {state(meta, today)}"
        )
    for name in problems:
        print(f"{name:<28} invalid, run check")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description="Check and index Wayfinder decision cards.")
    parser.add_argument("command", choices=["check", "index", "status", "fixture"])
    parser.add_argument("--cards-dir", default=None, help="directory holding the card files")
    parser.add_argument(
        "--target",
        choices=["pi", "claude", "all"],
        default=None,
        help="target harness when --cards-dir is omitted (default: 'pi' for status, 'all' otherwise)",
    )
    parser.add_argument("--today", help="override today's date (YYYY-MM-DD), for testing")
    args = parser.parse_args(argv)
    today = datetime.date.fromisoformat(args.today) if args.today else datetime.date.today()
    command = {"check": cmd_check, "index": cmd_index, "status": cmd_status, "fixture": cmd_fixture}[args.command]

    if args.cards_dir is not None:
        return command(args.cards_dir, today)

    target = args.target or ("pi" if args.command == "status" else "all")
    selected = [TARGETS["pi"], TARGETS["claude"]] if target == "all" else [TARGETS[target]]

    exit_code = 0
    for idx, cfg in enumerate(selected):
        if idx > 0 and args.command == "status":
            print()
        rc = command(cfg["cards_dir"], today)
        if rc != 0:
            exit_code = rc
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
